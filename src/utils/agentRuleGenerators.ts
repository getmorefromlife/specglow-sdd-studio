import type { SddArtifactPackage } from '../types'

/**
 * Synthesizes platform, tech stack, and i18n/RTL guidelines for AI coding agents.
 */
function getPlatformStackDirectives(pkg: SddArtifactPackage): string {
  const parts: string[] = []

  const target = pkg.platformTarget || 'web-portal'
  const stack = pkg.techStack || 'nextjs-shadcn'

  parts.push(`- **Platform Target:** \`${target}\``)
  parts.push(`- **Enforced Tech Stack:** \`${stack}\``)

  if (stack === 'nextjs-shadcn') {
    parts.push(`- **UI Library Invariant:** Strictly import UI components from \`@/components/ui\` (shadcn/ui primitives). Never install unvetted external component kits or arbitrary CSS frameworks.`)
    parts.push(`- **Routing & Rendering:** Next.js 15 App Router. Maintain strict separation between Server Components (data fetching) and Client Components (\`'use client'\` for user interactivity).`)
  } else if (stack === 'react-native') {
    parts.push(`- **Mobile UI & Styling:** React Native with Expo SDK 52 and NativeWind v4 (Tailwind). Enforce a minimum 48px touch target on all interactive controls.`)
    parts.push(`- **Offline Storage:** Use SQLite via \`expo-sqlite\` or WatermelonDB with CRDT reconciliation for offline-first data persistence.`)
  } else if (stack === 'astro-content') {
    parts.push(`- **Static & Documentation:** Astro 5 Content Collections with Tailwind CSS & MDX. Zero unnecessary clientside JavaScript.`)
  } else if (stack === 'flutter-dart') {
    parts.push(`- **Flutter Directives:** Flutter 3.x with Dart and Material 3 design system. Strict state management via Riverpod.`)
  } else if (stack === 'fastapi-react') {
    parts.push(`- **Full-Stack Split:** FastAPI (Python 3.12, Pydantic v2) backend adhering to OpenAPI contracts + React 19 SPA with Tailwind CSS.`)
  }

  if (target === 'mobile-app') {
    parts.push(`- **Mobile Invariants:** Enforce iOS/Android Safe Area Insets (\`react-native-safe-area-context\`), APNs/FCM background token management, and deep linking via universal links.`)
  } else if (target === 'web-portal') {
    parts.push(`- **Web Portal Invariants:** Guarantee 90+ Core Web Vitals (LCP < 2.5s, INP < 200ms, CLS < 0.1), OpenGraph metadata on every page, and semantic HTML5 landmarks.`)
  }

  if (pkg.enableRtlMultilingual) {
    parts.push(`- **Multilingual & RTL Invariant (Arabic / Urdu / English):**`)
    parts.push(`  * Use CSS logical properties (\`ms-\`, \`me-\`, \`ps-\`, \`pe-\`, \`start-\`, \`end-\`) rather than physical directional properties (\`ml-\`, \`mr-\`, \`pl-\`, \`pr-\`).`)
    parts.push(`  * Dynamic \`dir="rtl"\` attribute switching on root and card containers for right-to-left scripts.`)
    parts.push(`  * Include Google Noto Naskh Arabic and Noto Nastaliq Urdu font fallbacks for typography rendering.`)
  }

  return parts.join('\n')
}

/**
 * Generates CLAUDE.md tailored specifically for Anthropic's Claude Code CLI.
 * Enforces non-negotiable architectural boundaries, security invariants,
 * and test-driven convergence loops.
 */
export function generateClaudeMd(pkg: SddArtifactPackage): string {
  const c = pkg.constitution
  const tg = pkg.taskGraph
  const sampleTest = tg.tasks[0]?.acceptanceTestCriteria || 'npm test'

  const jurTag = pkg.jurisdiction ? ` | Jurisdiction: ${pkg.jurisdiction}` : ''
  const platformTag = pkg.platformTarget ? ` | Platform: ${pkg.platformTarget}` : ''
  const stackTag = pkg.techStack ? ` | Stack: ${pkg.techStack}` : ''

  return `# CLAUDE.md - Agent Instructions for ${pkg.title}
Generated by SpecGlow SDD Studio • ${pkg.createdAt}
Domain: ${pkg.domain} | Rigor Depth: ${pkg.targetDepth}${jurTag}${platformTag}${stackTag}

## 🎯 Project Overview & Objective
${c.systemOverview}

---

## 🏗️ Platform, Stack & UI Directives
${getPlatformStackDirectives(pkg)}

---

## 🛡️ INVARIANT: APPROVED ECOSYSTEM PACKAGES ONLY (ZERO-SLOPSQUATTING)
- AI coding agents must NEVER install unvetted or hallucinated third-party libraries.
- **Auth:** Native \`jose\` or \`@auth/core\`.
- **Database:** Parameterized queries or approved ORM (\`@prisma/client\`, \`drizzle-orm\`). Raw SQL concatenation is strictly forbidden.
- **Crypto:** Web Crypto API or Node native \`crypto\` only.

---

## 🚨 Non-Negotiable Invariants & Constitution
Strictly adhere to these security and architectural invariants during all execution steps:
${c.securityInvariants.map(si => `- **[${si.id}] (${si.category})**: ${si.invariant}\n  *Enforcement:* \`${si.enforcementMechanism}\``).join('\n')}

---

## 🚫 Out of Scope (Explicit Anti-Requirements)
Do NOT implement, hallucinate, or accept user proposals for the following:
${c.antiRequirements.map(ar => `- ❌ **[${ar.id}] ${ar.item}**: ${ar.reason}`).join('\n')}

---

## 🛠️ Technical Constraints & Stack Guidelines
| Category | Enforced Standard | Architectural Rationale |
| :--- | :--- | :--- |
${c.technicalConstraints.map(tc => `| **${tc.category}** | ${tc.rule} | ${tc.rationale} |`).join('\n')}

---

## 📋 Task Execution Protocol
Execute implementation tasks defined in \`tasks.md\` sequentially:
1. **Target Verification:** Review \`tasks.md\` to identify active blockers and target file paths.
2. **Atomic Changes:** Only modify files designated for the current task.
3. **Compile-Test Loop:** Immediately after modifying or generating code, run acceptance verification:
   \`\`\`bash
   ${sampleTest}
   \`\`\`
4. **Invariant Check:** Verify no security invariants or anti-requirements have been compromised.
`
}

