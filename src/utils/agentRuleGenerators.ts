import type { SddArtifactPackage } from '../types'

/**
 * Generates CLAUDE.md tailored specifically for Anthropic's Claude Code CLI.
 * Enforces non-negotiable architectural boundaries, security invariants,
 * and test-driven convergence loops.
 */
export function generateClaudeMd(pkg: SddArtifactPackage): string {
  const c = pkg.constitution
  const tg = pkg.taskGraph
  const sampleTest = tg.tasks[0]?.acceptanceTestCriteria || 'npm test'

  const jurTag = pkg.jurisdiction ? ` | Jurisdiction: ${pkg.jurisdiction}` : ''

  return `# CLAUDE.md - Agent Instructions for ${pkg.title}
Generated by SpecGlow SDD Studio • ${pkg.createdAt}
Domain: ${pkg.domain} | Rigor Depth: ${pkg.targetDepth}${jurTag}

## 🎯 Project Overview & Objective
${c.systemOverview}

---

## 🛡️ INVARIANT: APPROVED ECOSYSTEM PACKAGES ONLY (ZERO-SLOPSQUATTING)
- AI coding agents must NEVER install unvetted or hallucinated third-party libraries.
- **Auth:** Native \`jose\` or \`@auth/core\`.
- **Database:** Parameterized queries or approved ORM (\`@prisma/client\`, \`drizzle-orm\`). Raw SQL concatenation is strictly forbidden.
- **Crypto:** Web Crypto API or Node native \`crypto\` only.

---

## 🚨 Non-Negotiable Invariants & Constitution
Strictly adhere to these security and architectural invariants during all execution steps:
${c.securityInvariants.map(si => `- **[${si.id}] (${si.category})**: ${si.invariant}\n  *Enforcement:* \`${si.enforcementMechanism}\``).join('\n')}

---

## 🚫 Out of Scope (Explicit Anti-Requirements)
Do NOT implement, hallucinate, or accept user proposals for the following:
${c.antiRequirements.map(ar => `- ❌ **[${ar.id}] ${ar.item}**: ${ar.reason}`).join('\n')}

---

## 🛠️ Technical Constraints & Stack Guidelines
| Category | Enforced Standard | Architectural Rationale |
| :--- | :--- | :--- |
${c.technicalConstraints.map(tc => `| **${tc.category}** | ${tc.rule} | ${tc.rationale} |`).join('\n')}

---

## 📋 Task Execution Protocol
Execute implementation tasks defined in \`tasks.md\` sequentially:
1. **Target Verification:** Review \`tasks.md\` to identify active blockers and target file paths.
2. **Atomic Changes:** Only modify files designated for the current task.
3. **Compile-Test Loop:** Immediately after modifying or generating code, run acceptance verification:
   \`\`\`bash
   ${sampleTest}
   \`\`\`
4. **Invariant Check:** Verify no security invariants or anti-requirements have been compromised.
`
}

/**
 * Generates AGENTS.md - The universal standard for autonomous AI coding agents
 * (Google Antigravity, Cursor, Devin, GitHub Copilot Workspace, Codex).
 */
export function generateAgentsMd(pkg: SddArtifactPackage): string {
  const c = pkg.constitution
  const tg = pkg.taskGraph
  const jurTag = pkg.jurisdiction ? ` | Jurisdiction: ${pkg.jurisdiction}` : ''

  return `# AGENTS.md - Universal AI Agent Operational Directive
Initiative: ${pkg.title}
Domain: ${pkg.domain} | Delivery Rigor: ${pkg.targetDepth}${jurTag}
Generated by SpecGlow SDD Studio (Syed Imon Rizvi, PMP®, PSM II)

## 1. System Role & Autonomous Execution Benchmark
You are operating as a Principal Systems Engineer executing tasks from an enterprise Spec-Driven Development (SDD) contract.
You must treat this specification suite as an immutable boundary unless explicitly instructed otherwise.

## 2. Hard Invariants (Zero Exceptions)
${c.securityInvariants.map((si, i) => `${i + 1}. **[${si.category}]**: ${si.invariant} (Enforcement: ${si.enforcementMechanism})`).join('\n')}

## 3. Explicit Anti-Requirements (Forbidden Scope)
${c.antiRequirements.map(ar => `- **FORBIDDEN [${ar.id}]**: ${ar.item} — ${ar.reason}`).join('\n')}

## 4. Architectural Rules
${c.technicalConstraints.map(tc => `- **${tc.category}**: ${tc.rule}`).join('\n')}

## 5. Implementation Task Graph
Refer to \`tasks.md\` for the dependency graph. Total estimated cycle time: ~${tg.totalEstimatedAgentMinutes} minutes.
Always check the \`Blocked By\` array before initiating a task.
`
}

/**
 * Generates .cursorrules for Cursor IDE and Windsurf.
 */
export function generateCursorRules(pkg: SddArtifactPackage): string {
  const c = pkg.constitution
  const constraints = c.technicalConstraints.map(tc => `- ${tc.category}: ${tc.rule}`).join('\n')
  const invariants = c.securityInvariants.map(si => `- ${si.category}: ${si.invariant}`).join('\n')
  const antiReqs = c.antiRequirements.map(ar => `- ${ar.item}`).join('\n')

  return `# .cursorrules - Project Instructions for ${pkg.title}

You are an expert full-stack engineer working on ${pkg.title} (${pkg.domain} domain).

## Core Principles
- Strictly adhere to Spec-Driven Development (SDD) principles.
- Check tasks.md for task dependencies and target files.
- Never write ad-hoc code that violates the Project Constitution (constitution.md).

## Technical Constraints
${constraints}

## Security & Compliance Invariants
${invariants}

## Explicitly Out of Scope
${antiReqs}

## Coding Style & Quality Assurance
- Strict TypeScript types (no 'any').
- Always implement defensive error boundaries and visual feedback states.
- Follow atomic, single-responsibility modular architecture.
- Run tests and linting after every code modification.
`
}
