/**
 * Generates .cursorrules for Cursor IDE and Windsurf.
 */
export function generateCursorRules(pkg: SddArtifactPackage): string {
  const c = pkg.constitution
  const constraints = c.technicalConstraints.map(tc => `- ${tc.category}: ${tc.rule}`).join('\n')
  const invariants = c.securityInvariants.map(si => `- ${si.category}: ${si.invariant}`).join('\n')
  const antiReqs = c.antiRequirements.map(ar => `- ${ar.item}`).join('\n')

  return `# .cursorrules - Project Instructions for ${pkg.title}

You are an expert full-stack engineer working on ${pkg.title} (${pkg.domain} domain).

## Platform, Stack & UI Directives
${getPlatformStackDirectives(pkg)}

## Core Principles
- Strictly adhere to Spec-Driven Development (SDD) principles.
- Check tasks.md for task dependencies and target files.
- Never write ad-hoc code that violates the Project Constitution (constitution.md).

## Technical Constraints
${constraints}

## Security & Compliance Invariants
${invariants}

## Explicitly Out of Scope
${antiReqs}

## Coding Style & Quality Assurance
- Strict TypeScript types (no 'any').
- Always implement defensive error boundaries and visual feedback states.
- Follow atomic, single-responsibility modular architecture.
- Run tests and linting after every code modification.
`
}
