export function generateConstitutionMarkdown(pkg: SddArtifactPackage): string {
  const c = pkg.constitution
  const jurTag = pkg.jurisdiction ? ` | Jurisdiction: ${pkg.jurisdiction}` : ''
  
  let strideSection = ''
  if (c.strideThreatMatrix && c.strideThreatMatrix.length > 0) {
    strideSection = `\n## 4. STRIDE Threat Modeling Matrix\n| Threat Category | Assessed Threat Scenario | Enforced Architectural Countermeasure |\n| :--- | :--- | :--- |\n` +
      c.strideThreatMatrix.map(st => `| **${st.category}** | ${st.threat} | ${st.architecturalMitigation} |`).join('\n') +
      '\n'
  }

  const antiReqIndex = strideSection ? '5' : '4'

  return `# Project Constitution: ${pkg.title}
Generated by SpecGlow SDD Studio • ${pkg.createdAt}
Domain: ${pkg.domain} | Rigor Depth: ${pkg.targetDepth}${jurTag}

## 1. System Architecture Overview
${c.systemOverview}

## 2. Non-Negotiable Technical Constraints
| Category | Rule | Engineering Rationale |
| :--- | :--- | :--- |
${c.technicalConstraints.map(tc => `| **${tc.category}** | ${tc.rule} | ${tc.rationale} |`).join('\n')}

## 3. Security Invariants & Compliance Rules
| ID | Category | Non-Negotiable Invariant | Enforcement Mechanism |
| :--- | :--- | :--- | :--- |
${c.securityInvariants.map(si => `| **${si.id}** | ${si.category} | ${si.invariant} | ${si.enforcementMechanism} |`).join('\n')}
${strideSection}
## ${antiReqIndex}. Explicit Anti-Requirements (Strictly OUT OF SCOPE)
> The following capabilities are explicitly forbidden from implementation during this lifecycle to prevent AI and agent scope creep:

${c.antiRequirements.map(ar => `- **[${ar.id}] ${ar.item}**: ${ar.reason}`).join('\n')}
`
}

